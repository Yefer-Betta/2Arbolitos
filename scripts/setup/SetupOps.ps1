function Wait-SystemHealth {
    param([int]$TimeoutSec = 180)

    $healthUrl = (Get-AccessUrl) + '/api/health'
    $deadline = (Get-Date).AddSeconds($TimeoutSec)

    while ((Get-Date) -lt $deadline) {
        $api = Test-HttpStatus -Url $healthUrl -TimeoutSec 4
        if ($api -eq 200) {
            return [pscustomobject]@{ Ok = $true; Api = $api; Logs = ''; Broken = '' }
        }

        $ps = Get-ComposePs
        foreach ($service in @('db', 'backend', 'frontend')) {
            if (-not $ps.ContainsKey($service)) { continue }
            $item = $ps[$service]
            if ($item.State -eq 'exited' -or $item.State -eq 'restarting' -or $item.State -eq 'dead') {
                $logs = Get-LogsSnapshot -Service $service -Tail 80
                return [pscustomobject]@{ Ok = $false; Api = $api; Logs = $logs; Broken = $service }
            }
        }

        Start-Sleep -Seconds 2
    }

    return [pscustomobject]@{
        Ok     = $false
        Api    = (Test-HttpStatus -Url $healthUrl -TimeoutSec 4)
        Logs   = (Get-LogsSnapshot -Service 'backend' -Tail 100)
        Broken = 'timeout'
    }
}

function Test-ApiLogin {
    param([string]$BaseUrl)
    try {
        $request = [System.Net.HttpWebRequest]::Create($BaseUrl + '/api/auth/login')
        $request.Method = 'POST'
        $request.ContentType = 'application/json'
        $request.Proxy = $null
        $request.Timeout = 8000
        $body = '{"username":"admin","password":"admin123"}'
        $bytes = [System.Text.Encoding]::UTF8.GetBytes($body)
        $request.ContentLength = $bytes.Length
        $stream = $request.GetRequestStream()
        $stream.Write($bytes, 0, $bytes.Length)
        $stream.Close()
        $response = $request.GetResponse()
        $code = [int]$response.StatusCode
        $response.Close()
        return $code
    } catch [System.Net.WebException] {
        if ($_.Exception.Response) { return [int]$_.Exception.Response.StatusCode }
        return 0
    } catch {
        return 0
    }
}

