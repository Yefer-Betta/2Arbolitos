$Script:SelfTestFailures = 0

function Check {
    param([string]$Name, [bool]$Condition, [string]$Detail = '')
    if ($Condition) {
        Write-Host ("[ok   ] " + $Name)
    } else {
        $Script:SelfTestFailures++
        $extra = if ($Detail) { " -> $Detail" } else { '' }
        Write-Host ("[FALLO] " + $Name + $extra)
    }
}

function Invoke-SetupSelfTest {
    Write-Host ''
    Write-Host '2Arbolitos - autotest del instalador'
    Write-Host ("Raiz: " + $Script:Root)
    Write-Host ''

    $fixtures = Join-Path $PSScriptRoot 'fixtures'
    $expected = @{
        'env-stale'     = 'ENV_STALE'
        'db-password'   = 'DB_PASSWORD'
        'name-conflict' = 'NAME_CONFLICT'
        'port-busy'     = 'PORT_BUSY'
        'engine-off'    = 'ENGINE_OFF'
        'pull-fail'     = 'PULL_FAIL'
        'migration'     = 'MIGRATION'
    }

    if (Test-Path -LiteralPath $fixtures) {
        $files = @(Get-ChildItem -LiteralPath $fixtures -Filter '*.log' -File)
        Check 'Hay fixtures de errores' ($files.Count -ge 7) ("encontrados: " + $files.Count)
        foreach ($file in $files) {
            $code = $expected[$file.BaseName]
            if (-not $code) { continue }
            $text = [System.IO.File]::ReadAllText($file.FullName, [System.Text.Encoding]::UTF8)
            $info = Get-FailureInfo -Text $text
            Check ("Clasifica " + $file.Name) ($info.Code -eq $code) ("esperado $code, obtenido " + $info.Code)
        }
    } else {
        Check 'Carpeta de fixtures' $false $fixtures
    }

    $text = New-EnvContent -Port 8080 -HostIp '192.168.1.50' -DbPassword ('a' * 32) -JwtSecret ('b' * 47)
    $map = @{}
    foreach ($line in ($text -split "`r`n")) {
        if ($line -match '^([A-Z_]+)=(.*)$') { $map[$matches[1]] = $matches[2] }
    }
    Check 'El .env generado tiene 4 claves' ($map.Count -eq 4) ("claves: " + $map.Count)
    Check 'El puerto se escribe en .env' ($map['FRONTEND_PORT'] -eq '8080') ([string]$map['FRONTEND_PORT'])
    Check 'La IP se escribe en .env' ($map['HOST_IP'] -eq '192.168.1.50') ([string]$map['HOST_IP'])
    Check 'El secreto de la base tiene 32 caracteres' ($map['MYSQL_ROOT_PASSWORD'].Length -eq 32)

    $free = Find-FreePort -Start 18080 -Count 5
    Check 'Encuentra un puerto libre' ($free -gt 0) ([string]$free)

    $status = Get-SetupStatus
    Check 'El estado se calcula' ($null -ne $status -and $status.Mode -ne '') ([string]$status.Mode)
    Check 'El estado incluye hallazgos' ($null -ne $status.Findings)
    Check 'El estado incluye contenedores' ($null -ne $status.Containers)

    Write-Host ''
    if ($Script:SelfTestFailures -eq 0) {
        Write-Host 'Todo correcto.'
        exit 0
    }
    Write-Host ("Fallos: " + $Script:SelfTestFailures)
    exit 1
}

