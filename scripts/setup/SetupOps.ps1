function Invoke-Repair {
    param([string]$Id)

    if (-not $Id) {
        Stop-Setup -Code 'REPAIR' -Title 'No se indico que corregir' -Detail 'Falta el identificador del hallazgo.' -Hints @()
    }

    Write-Event -Type 'plan' -Data @{ steps = @(@{ id = 'fix'; label = 'Reparacion' }) }
    Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'run'; text = 'Aplicando la correccion...' }

    switch ($Id) {
        'env' {
            [void](Initialize-Env)
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Configuracion corregida' }
        }
        'engine' {
            if (-not (Open-DockerDesktop)) {
                Stop-Setup -Code 'ENGINE_OFF' -Title 'No se encontro Docker Desktop' `
                    -Detail 'Abrelo manualmente y vuelve a intentar.' -Hints @('Inicio > Docker Desktop')
            }
            $deadline = (Get-Date).AddSeconds(150)
            while ((Get-Date) -lt $deadline) {
                Start-Sleep -Seconds 3
                if (Test-DockerEngine -Force) { break }
            }
            if (-not (Test-DockerEngine -Force)) {
                Stop-Setup -Code 'ENGINE_OFF' -Title 'Docker no respondio' `
                    -Detail 'Docker Desktop no arranco en 150 segundos.' `
                    -Hints @('Abrelo manualmente y espera a que diga "Engine running".')
            }
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Docker Desktop respondiendo' }
        }
        'start' {
            $up = Invoke-SetupNative -Tokens @('compose', 'up', '-d') -TimeoutSec 300
            if ($up.ExitCode -ne 0) {
                $info = Get-FailureInfo -Text (([string]$up.Out) + "`n" + ([string]$up.Err))
                Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
            }
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Contenedores iniciados' }
        }
        'recreate' {
            $recreate = Invoke-SetupNative -Tokens @('compose', 'up', '-d', '--force-recreate', 'backend', 'frontend') -TimeoutSec 300
            if ($recreate.ExitCode -ne 0) {
                $info = Get-FailureInfo -Text (([string]$recreate.Out) + "`n" + ([string]$recreate.Err))
                Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
            }
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Contenedores recreados con la configuracion actual' }
        }
        'restart' {
            $restart = Invoke-SetupNative -Tokens @('compose', 'restart') -TimeoutSec 240
            if ($restart.ExitCode -ne 0) {
                $info = Get-FailureInfo -Text (([string]$restart.Out) + "`n" + [string]$restart.Err)
                Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
            }
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Sistema reiniciado' }
        }
        'dbpass' {
            $previous = Get-PreviousDbPassword
            if (-not $previous) {
                Stop-Setup -Code 'DB_PASSWORD' -Title 'No hay una contrasena anterior que reutilizar' `
                    -Detail 'El contenedor de la base ya no existe, asi que solo queda reiniciar la base (se pierden los datos).' `
                    -Hints @('Usa "Desinstalar" marcando la base de datos y vuelve a instalar.')
            }
            Set-EnvValues -Values @{ MYSQL_ROOT_PASSWORD = $previous }
            $recreate = Invoke-SetupNative -Tokens @('compose', 'up', '-d', '--force-recreate', 'db', 'backend') -TimeoutSec 300
            if ($recreate.ExitCode -ne 0) {
                $info = Get-FailureInfo -Text (([string]$recreate.Out) + "`n" + [string]$recreate.Err)
                Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
            }
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Contrasena anterior recuperada; los datos se conservan' }
        }
        'firewall' {
            $port = [int](Get-FrontendPort)
            if (-not (Add-FirewallRule -Port $port)) {
                Stop-Setup -Code 'FIREWALL' -Title 'No se pudo configurar el firewall' `
                    -Detail 'Se necesitan permisos de administrador.' `
                    -Hints @('Cierra el instalador y vuelve a abrirlo como administrador.')
            }
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = "Puerto $port permitido" }
        }
        'orphans' {
            [void](Invoke-SetupNative -Tokens @('compose', 'down', '--remove-orphans') -TimeoutSec 120)
            [void](Invoke-SetupNative -Tokens @('compose', 'up', '-d') -TimeoutSec 300)
            Write-Event -Type 'step' -Data @{ id = 'fix'; state = 'ok'; text = 'Restos eliminados' }
        }
        default {
            Stop-Setup -Code 'REPAIR' -Title 'Correccion no disponible' `
                -Detail "No se conoce la accion '$Id'." -Hints @('Ejecuta el diagnostico del panel para ver mas detalles.')
        }
    }

    $health = Wait-SystemHealth -TimeoutSec 120
    if (-not $health.Ok) {
        $info = Get-FailureInfo -Text ([string]$health.Logs)
        Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
    }

    Write-Event -Type 'done' -Data @{
        message = 'Correccion aplicada y sistema respondiendo'
        url     = (Get-AccessUrl)
        lanUrl  = (Get-LanUrl)
    }
}

# ---------------------------------------------------------------------------
# Desinstalacion
# ---------------------------------------------------------------------------

function Invoke-Uninstall {
    param(
        [switch]$RemoveVolume,
        [switch]$RemoveEnv,
        [switch]$RemoveBackups,
        [switch]$RemoveFirewall,
        [switch]$KeepImages,
        [switch]$BackupBefore
    )

    $plan = @(
        @{ id = 'backup';     label = 'Respaldo de seguridad' },
        @{ id = 'containers'; label = 'Contenedores y red' },
        @{ id = 'images';     label = 'Imagenes del proyecto' },
        @{ id = 'data';       label = 'Base de datos' },
        @{ id = 'env';        label = 'Configuracion (.env)' },
        @{ id = 'backups';    label = 'Respaldos' },
        @{ id = 'firewall';   label = 'Regla de firewall' }
    )
    Write-Event -Type 'plan' -Data @{ steps = $plan }

    if ($BackupBefore) {
        Write-Event -Type 'step' -Data @{ id = 'backup'; state = 'run'; text = 'Creando un respaldo antes de desinstalar...' }
        try {
            $message = New-ArbolitosBackup
            Write-Event -Type 'step' -Data @{ id = 'backup'; state = 'ok'; text = $message }
        } catch {
            Write-Event -Type 'step' -Data @{ id = 'backup'; state = 'skip'; text = 'No se pudo crear el respaldo (la base no esta corriendo)' }
        }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'backup'; state = 'skip'; text = 'Respaldo previo omitido' }
    }

    Write-Event -Type 'step' -Data @{ id = 'containers'; state = 'run'; text = 'Deteniendo y eliminando contenedores...' }
    $tokens = @('compose', 'down')
    if ($RemoveVolume) { $tokens += '-v' }
    $down = Invoke-SetupNative -Tokens $tokens -TimeoutSec 180

    if ($down.ExitCode -ne 0) {
        Write-Event -Type 'log' -Data @{ text = 'Compose fallo; eliminando contenedores por nombre...' }
        foreach ($name in @('2arbolitos-frontend', '2arbolitos-backend', '2arbolitos-db')) {
            [void](Invoke-SetupNative -Tokens @('rm', '-f', $name) -TimeoutSec 60)
        }
        [void](Invoke-SetupNative -Tokens @('network', 'rm', '2arboltos_2arbolitos-net') -TimeoutSec 30)
    }
    Write-Event -Type 'step' -Data @{ id = 'containers'; state = 'ok'; text = 'Contenedores eliminados' }

    if (-not $KeepImages) {
        Write-Event -Type 'step' -Data @{ id = 'images'; state = 'run'; text = 'Eliminando imagenes del proyecto...' }
        foreach ($image in @('2arbolitos-backend', '2arbolitos-frontend')) {
            [void](Invoke-SetupNative -Tokens @('image', 'rm', '-f', $image) -TimeoutSec 60)
        }
        Write-Event -Type 'step' -Data @{ id = 'images'; state = 'ok'; text = 'Imagenes eliminadas' }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'images'; state = 'skip'; text = 'Imagenes conservadas' }
    }

    if ($RemoveVolume) {
        Write-Event -Type 'step' -Data @{ id = 'data'; state = 'run'; text = 'Eliminando la base de datos...' }
        $volumes = Invoke-SetupNative -Tokens @('volume', 'ls', '--format', '{{.Name}}') -TimeoutSec 30
        foreach ($line in (([string]$volumes.Out) -split "`r?`n")) {
            $name = $line.Trim()
            if ($name -match 'mysql_data$' -and $name -match 'arbol') {
                [void](Invoke-SetupNative -Tokens @('volume', 'rm', $name) -TimeoutSec 60)
            }
        }
        Write-Event -Type 'step' -Data @{ id = 'data'; state = 'ok'; text = 'Base de datos eliminada' }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'data'; state = 'skip'; text = 'Base de datos conservada' }
    }

    if ($RemoveEnv) {
        Write-Event -Type 'step' -Data @{ id = 'env'; state = 'run'; text = 'Eliminando la configuracion...' }
        $envFile = Join-Path $Script:Root '.env'
        foreach ($file in @($envFile, ($envFile + '.bak'))) {
            if (-not (Test-Path -LiteralPath $file)) { continue }
            if ($Script:DryRunMode) {
                Write-Log "SIMULADO: borrar $file"
            } else {
                Remove-Item -LiteralPath $file -Force -ErrorAction SilentlyContinue
            }
        }
        Write-Event -Type 'step' -Data @{ id = 'env'; state = 'ok'; text = 'Configuracion eliminada' }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'env'; state = 'skip'; text = 'Configuracion conservada' }
    }

    if ($RemoveBackups) {
        Write-Event -Type 'step' -Data @{ id = 'backups'; state = 'run'; text = 'Eliminando respaldos...' }
        $dir = Join-Path $Script:Root 'backups'
        if (Test-Path -LiteralPath $dir) {
            if ($Script:DryRunMode) {
                Write-Log "SIMULADO: borrar $dir"
            } else {
                Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
            }
        }
        Write-Event -Type 'step' -Data @{ id = 'backups'; state = 'ok'; text = 'Respaldos eliminados' }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'backups'; state = 'skip'; text = 'Respaldos conservados' }
    }

    if ($RemoveFirewall) {
        Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'run'; text = 'Quitando la regla de firewall...' }
        [void](Remove-FirewallRule)
        Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'ok'; text = 'Regla de firewall eliminada' }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'skip'; text = 'Regla de firewall conservada' }
    }

    $note = if ($RemoveVolume) {
        'La base de datos y sus datos fueron eliminados.'
    } else {
        'Los datos de la base se conservaron.'
    }
    Write-Event -Type 'done' -Data @{
        message = 'Desinstalacion completada'
        note    = $note
        logFile = $Script:LogPath
    }
}

