function Write-Event {
    param(
        [Parameter(Mandatory = $true)][string]$Type,
        [hashtable]$Data = @{}
    )

    $payload = @{ t = $Type }
    foreach ($key in $Data.Keys) { $payload[$key] = $Data[$key] }

    if ($Script:ProgressPath) {
        try {
            $json = $payload | ConvertTo-Json -Compress -Depth 5
            [System.IO.File]::AppendAllText($Script:ProgressPath, $json + "`n", $Script:Utf8NoBom)
        } catch { }
    }

    switch ($Type) {
        'step' {
            $state = [string]$Data.state
            $text = [string]$Data.text
            if ($state -eq 'run') { Write-Host ("[..] " + $text) }
            elseif ($state -eq 'ok') { Write-Host ("[OK] " + $text) }
            elseif ($state -eq 'skip') { Write-Host ("[--] " + $text) }
            elseif ($state -eq 'bad') { Write-Host ("[!!] " + $text) }
        }
        'log' {
            Write-Host ("     " + [string]$Data.text)
        }
        'done' {
            Write-Host ''
            Write-Host ("[OK] " + [string]$Data.message)
        }
        'fail' {
            Write-Host ''
            Write-Host ("[ERROR] " + [string]$Data.title)
            if ($Data.detail) { Write-Host ("        " + [string]$Data.detail) }
            foreach ($hint in @($Data.hints)) {
                if ($hint) { Write-Host ("        - " + [string]$hint) }
            }
        }
    }
}

function Start-SetupLog {
    $dir = Join-Path $Script:Root 'logs'
    if (-not (Test-Path -LiteralPath $dir)) {
        [void](New-Item -ItemType Directory -Path $dir)
    }
    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    $Script:LogPath = Join-Path $dir "instalacion-$stamp.log"
    $header = @(
        "2Arbolitos POS - registro de instalacion",
        "Fecha: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')",
        "Accion: $Action",
        "Equipo: $env:COMPUTERNAME",
        "PowerShell: $($PSVersionTable.PSVersion)",
        ("-" * 60)
    ) -join "`r`n"
    [System.IO.File]::WriteAllText($Script:LogPath, $header + "`r`n", $Script:Utf8NoBom)
    return $Script:LogPath
}

function Write-Log {
