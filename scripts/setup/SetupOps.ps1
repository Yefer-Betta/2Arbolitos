function Invoke-SetupEntry {
    switch ($Action) {
        'Status' {
            $status = Get-SetupStatus
            $json = $status | ConvertTo-Json -Depth 6 -Compress
            if ($Script:ProgressPath) {
                [System.IO.File]::WriteAllText($Script:ProgressPath, $json, $Script:Utf8NoBom)
            }
            Write-Output $json
            exit 0
        }
        'Install' {
            [void](Start-SetupLog)
            try {
                Install-Arbolitos -Port $Port -SkipShortcut:$SkipShortcut
                exit 0
            } catch {
                if ($Script:Failure) {
                    Write-Event -Type 'fail' -Data @{
                        code   = $Script:Failure.Code
                        title  = $Script:Failure.Title
                        detail = $Script:Failure.Detail
                        hints  = $Script:Failure.Hints
                    }
                } else {
                    $info = Get-FailureInfo -Text $_.Exception.Message
                    Write-Event -Type 'fail' -Data @{
                        code   = $info.Code
                        title  = $info.Title
                        detail = $info.Detail
                        hints  = $info.Hints
                    }
                }
                Write-Log ('ERROR: ' + $_.Exception.Message)
                exit 2
            }
        }
        'Repair' {
            [void](Start-SetupLog)
            try {
                Invoke-Repair -Id $RepairId
                exit 0
            } catch {
                if ($Script:Failure) {
                    Write-Event -Type 'fail' -Data @{
                        code   = $Script:Failure.Code
                        title  = $Script:Failure.Title
                        detail = $Script:Failure.Detail
                        hints  = $Script:Failure.Hints
                    }
                } else {
                    $info = Get-FailureInfo -Text $_.Exception.Message
                    Write-Event -Type 'fail' -Data @{
                        code   = $info.Code
                        title  = $info.Title
                        detail = $info.Detail
                        hints  = $info.Hints
                    }
                }
                Write-Log ('ERROR: ' + $_.Exception.Message)
                exit 2
            }
        }
        'Uninstall' {
            [void](Start-SetupLog)
            try {
                Invoke-Uninstall -RemoveVolume:$RemoveVolume -RemoveEnv:$RemoveEnv `
                    -RemoveBackups:$RemoveBackups -RemoveFirewall:$RemoveFirewall `
                    -KeepImages:$KeepImages -BackupBefore:$BackupBefore
                exit 0
            } catch {
                $info = Get-FailureInfo -Text $_.Exception.Message
                Write-Event -Type 'fail' -Data @{
                    code   = $info.Code
                    title  = $info.Title
                    detail = $info.Detail
                    hints  = $info.Hints
                }
                Write-Log ('ERROR: ' + $_.Exception.Message)
                exit 2
            }
        }
        'SelfTest' {
            Invoke-SetupSelfTest
        }
    }
}

if ($MyInvocation.InvocationName -ne '.') {
    Invoke-SetupEntry
