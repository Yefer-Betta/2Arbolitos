function Test-Admin {
    try {
        $identity = [System.Security.Principal.WindowsIdentity]::GetCurrent()
        $principal = New-Object System.Security.Principal.WindowsPrincipal($identity)
        return $principal.IsInRole([System.Security.Principal.WindowsBuiltInRole]::Administrator)
    } catch {
        return $false
    }
}

function Get-PortOwner {
    param([int]$Port)
    try {
        $connection = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction Stop |
            Select-Object -First 1
        if (-not $connection) { return $null }
        $process = Get-Process -Id $connection.OwningProcess -ErrorAction SilentlyContinue
        return [pscustomobject]@{
            Pid  = [int]$connection.OwningProcess
            Name = if ($process) { $process.ProcessName } else { 'desconocido' }
        }
    } catch {
        try {
            $line = netstat -ano | Select-String -Pattern (":$Port\s+.*LISTENING") | Select-Object -First 1
            if ($line) {
                $parts = ($line.Line -split '\s+') | Where-Object { $_ }
                $pidValue = [int]$parts[-1]
                $process = Get-Process -Id $pidValue -ErrorAction SilentlyContinue
                return [pscustomobject]@{
                    Pid  = $pidValue
                    Name = if ($process) { $process.ProcessName } else { 'desconocido' }
                }
            }
        } catch { }
        return $null
    }
}

function Find-FreePort {
    param([int]$Start = 8080, [int]$Count = 20)
    for ($candidate = $Start; $candidate -lt ($Start + $Count); $candidate++) {
        if (-not (Test-Port -Port $candidate -TimeoutMs 300)) { return $candidate }
    }
    return 0
}

