function Test-FirewallRule {
    try {
        netsh advfirewall firewall show rule name="2Arbolitos" 2>&1 | Out-Null
        return ($LASTEXITCODE -eq 0)
    } catch {
        return $false
    }
}

function Add-FirewallRule {
    param([int]$Port = 80)
    if (-not (Test-Admin)) { return $false }
    if ($Script:DryRunMode) { Write-Log "SIMULADO: regla de firewall para el puerto $Port"; return $true }
    try {
        netsh advfirewall firewall delete rule name="2Arbolitos" 2>&1 | Out-Null
        netsh advfirewall firewall add rule name="2Arbolitos" dir=in action=allow protocol=TCP localport=$Port 2>&1 | Out-Null
        Write-Log "Regla de firewall configurada para el puerto $Port."
        return ($LASTEXITCODE -eq 0)
    } catch {
        return $false
    }
}

function Remove-FirewallRule {
    if (-not (Test-Admin)) { return $false }
    if ($Script:DryRunMode) { Write-Log 'SIMULADO: quitar regla de firewall'; return $true }
    try {
        netsh advfirewall firewall delete rule name="2Arbolitos" 2>&1 | Out-Null
        return ($LASTEXITCODE -eq 0)
    } catch {
        return $false
    }
}

