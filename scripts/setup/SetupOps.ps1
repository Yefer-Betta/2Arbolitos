function Get-EnvIssues {
    $file = Join-Path $Script:Root '.env'
    $issues = New-Object System.Collections.ArrayList
    $map = @{}

    if (-not (Test-Path -LiteralPath $file)) {
        [void]$issues.Add('missing')
        return [pscustomobject]@{ Issues = $issues; Map = $map }
    }

    try {
        $bytes = [System.IO.File]::ReadAllBytes($file)
        if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {
            [void]$issues.Add('bom')
        }
    } catch { }

    $map = Get-EnvMap

    foreach ($key in $Script:RequiredEnvKeys) {
        if (-not $map.ContainsKey($key) -or -not $map[$key]) {
            [void]$issues.Add('missing-key:' + $key)
        }
    }

    try {
        $seen = @{}
        foreach ($line in [System.IO.File]::ReadAllLines($file, [System.Text.Encoding]::UTF8)) {
            $text = $line.Trim()
            if (-not $text -or $text.StartsWith('#')) { continue }
            $index = $text.IndexOf('=')
            if ($index -lt 1) { continue }
            $key = $text.Substring(0, $index).Trim()
            if ($seen.ContainsKey($key)) {
                if (-not $issues.Contains('duplicate:' + $key)) { [void]$issues.Add('duplicate:' + $key) }
            } else {
                $seen[$key] = $true
            }
        }
    } catch { }

    if ($map.ContainsKey('JWT_SECRET') -and $Script:DefaultSecrets -contains $map['JWT_SECRET']) {
        [void]$issues.Add('default-secret')
    }

    if ($map.ContainsKey('HOST_IP')) {
        $current = Get-LocalIP
        if (-not $current) { $current = '127.0.0.1' }
        if ($map['HOST_IP'] -and $map['HOST_IP'] -ne '0.0.0.0' -and $map['HOST_IP'] -ne $current) {
            [void]$issues.Add('ip-stale')
        }
    }

    if ($map.ContainsKey('FRONTEND_PORT')) {
        $value = 0
        if (-not [int]::TryParse([string]$map['FRONTEND_PORT'], [ref]$value) -or $value -lt 1 -or $value -gt 65535) {
            [void]$issues.Add('bad-port')
        }
    }

    return [pscustomobject]@{ Issues = $issues; Map = $map }
}

function Set-EnvValues {
    param([hashtable]$Values)

    $file = Join-Path $Script:Root '.env'
    $lines = @()
    if (Test-Path -LiteralPath $file) {
        $lines = [System.IO.File]::ReadAllLines($file, [System.Text.Encoding]::UTF8)
    }

    $pending = @{}
    foreach ($key in $Values.Keys) { $pending[$key] = $Values[$key] }

    $output = New-Object System.Collections.ArrayList
    foreach ($line in $lines) {
        $text = $line.Trim()
        $index = $text.IndexOf('=')
        if ($index -gt 0 -and -not $text.StartsWith('#')) {
            $key = $text.Substring(0, $index).Trim()
            if ($pending.ContainsKey($key)) {
                [void]$output.Add("$key=$($pending[$key])")
                $pending.Remove($key)
                continue
            }
        }
        [void]$output.Add($line.TrimEnd())
    }
    foreach ($key in $pending.Keys) {
        [void]$output.Add("$key=$($pending[$key])")
    }

    if (Test-Path -LiteralPath $file) {
        Copy-Item -LiteralPath $file -Destination ($file + '.bak') -Force
    }

    $content = (($output -join "`r`n") + "`r`n")
    [System.IO.File]::WriteAllText($file, $content, $Script:Utf8NoBom)
    Write-Log "Configuracion actualizada: $($Values.Keys -join ', ')"
}

function New-EnvContent {
    param(
        [int]$Port = 80,
        [string]$HostIp = '',
        [string]$DbPassword = '',
        [string]$JwtSecret = ''
    )
    if (-not $DbPassword) { $DbPassword = [guid]::NewGuid().ToString('N') }
    if (-not $JwtSecret) { $JwtSecret = '2arbolitos_jwt_' + [guid]::NewGuid().ToString('N') }
    if (-not $HostIp) { $HostIp = Get-LocalIP }
    if (-not $HostIp) { $HostIp = '127.0.0.1' }
    if ($Port -lt 1 -or $Port -gt 65535) { $Port = 80 }

    $lines = @(
        "MYSQL_ROOT_PASSWORD=$DbPassword",
        "JWT_SECRET=$JwtSecret",
        "HOST_IP=$HostIp",
        "FRONTEND_PORT=$Port"
    )
    return (($lines -join "`r`n") + "`r`n")
}

function Initialize-Env {
    param([int]$Port = 0)

    $file = Join-Path $Script:Root '.env'
    $info = Get-EnvIssues
    $changed = $false

    if ($info.Issues.Contains('missing')) {
        $dbPassword = [guid]::NewGuid().ToString('N')
        $jwt = '2arbolitos_jwt_' + [guid]::NewGuid().ToString('N')
        $ip = Get-LocalIP
        $usePort = if ($Port -gt 0) { $Port } else { 80 }
        [System.IO.File]::WriteAllText($file, (New-EnvContent -Port $usePort -HostIp $ip -DbPassword $dbPassword -JwtSecret $jwt), $Script:Utf8NoBom)
        Write-Log 'Configuracion creada desde cero.'
        return [pscustomobject]@{
            Changed = $true
            Port    = $usePort
            HostIp  = $ip
            Backup  = $false
            Issues  = $info.Issues
        }
    }

    $values = @{}
    $map = $info.Map

    foreach ($key in $Script:RequiredEnvKeys) {
        if (-not $map.ContainsKey($key) -or -not $map[$key]) {
            switch ($key) {
                'MYSQL_ROOT_PASSWORD' { $values[$key] = [guid]::NewGuid().ToString('N') }
                'JWT_SECRET' { $values[$key] = '2arbolitos_jwt_' + [guid]::NewGuid().ToString('N') }
                'HOST_IP' { $values[$key] = (Get-LocalIP) }
                'FRONTEND_PORT' { $values[$key] = 80 }
            }
        }
    }

    if ($map.ContainsKey('JWT_SECRET') -and $Script:DefaultSecrets -contains $map['JWT_SECRET']) {
        $values['JWT_SECRET'] = '2arbolitos_jwt_' + [guid]::NewGuid().ToString('N')
    }

    $currentIp = Get-LocalIP
    if ($currentIp -and $map.ContainsKey('HOST_IP')) {
        if (-not $map['HOST_IP'] -or $map['HOST_IP'] -eq '0.0.0.0') {
            $values['HOST_IP'] = $currentIp
        }
    }

    $existingPort = 0
    if ($map.ContainsKey('FRONTEND_PORT')) {
        [void][int]::TryParse([string]$map['FRONTEND_PORT'], [ref]$existingPort)
    }

    if ($Port -gt 0) {
        if ($existingPort -ne $Port) { $values['FRONTEND_PORT'] = $Port }
    } elseif ($existingPort -lt 1 -or $existingPort -gt 65535) {
        $values['FRONTEND_PORT'] = 80
    }

    $backup = $false
    if ($values.Count -gt 0) {
        Set-EnvValues -Values $values
        $changed = $true
        $backup = Test-Path -LiteralPath ($file + '.bak')
        $map = Get-EnvMap
    }

    $finalPort = 80
    [void][int]::TryParse([string]$map['FRONTEND_PORT'], [ref]$finalPort)

    return [pscustomobject]@{
        Changed = $changed
        Port    = $finalPort
        HostIp  = [string]$map['HOST_IP']
        Backup  = $backup
        Issues  = $info.Issues
    }
}

