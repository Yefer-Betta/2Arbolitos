function Invoke-Stream {
    param(
        [string]$FileName,
        [string]$Arguments,
        [int]$TimeoutSec = 1800,
        [string]$WorkingDirectory = ''
    )

    if ($Script:DryRunMode) {
        Write-Log ('SIMULADO: ' + $FileName + ' ' + $Arguments)
        Write-Event -Type 'log' -Data @{ text = ('SIMULADO: ' + $FileName + ' ' + $Arguments) }
        return [pscustomobject]@{ ExitCode = 0; Out = ''; Err = ''; TimedOut = $false }
    }

    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $FileName
    $psi.Arguments = $Arguments
    $psi.UseShellExecute = $false
    $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.StandardOutputEncoding = [System.Text.Encoding]::UTF8
    $psi.StandardErrorEncoding = [System.Text.Encoding]::UTF8
    if ($WorkingDirectory) { $psi.WorkingDirectory = $WorkingDirectory }

    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $psi
    $buffer = New-Object System.Text.StringBuilder
    $timedOut = $false
    $err = ''

    try {
        [void]$process.Start()
        $errTask = $process.StandardError.ReadToEndAsync()
        $deadline = (Get-Date).AddSeconds($TimeoutSec)

        while (-not $process.StandardOutput.EndOfStream) {
            $line = $process.StandardOutput.ReadLine()
            if ($null -eq $line) { break }
            $clean = ($line -replace "`r", '').TrimEnd()
            if (-not $clean) { continue }
            if ($buffer.Length -lt 1048576) { [void]$buffer.AppendLine($clean) }
            Write-Log $clean
            Write-Event -Type 'log' -Data @{ text = $clean }
            if ((Get-Date) -gt $deadline) {
                $timedOut = $true
                try { $process.Kill() } catch { }
                break
            }
        }

        if (-not $process.WaitForExit(5000)) {
            try { $process.Kill() } catch { }
            $timedOut = $true
        }
        $err = [string]$errTask.Result
        if ($err.Trim()) { Write-Log ('[stderr] ' + $err.Trim()) }

        $code = if ($timedOut) { -1 } else { $process.ExitCode }
        if ($timedOut) {
            $err = "Tiempo de espera agotado ($TimeoutSec s)." + [Environment]::NewLine + $err
        }

        return [pscustomobject]@{
            ExitCode = $code
            Out      = $buffer.ToString()
            Err      = $err
            TimedOut = $timedOut
        }
    } catch {
        return [pscustomobject]@{
            ExitCode = -1
            Out      = $buffer.ToString()
            Err      = $_.Exception.Message
            TimedOut = $false
        }
    } finally {
        $process.Dispose()
    }
}

