    return [pscustomobject]@{
        Mode         = $mode
        Version      = (Get-AppVersion)
        Installed    = $installed
        Healthy      = $healthy
        Port         = $port
        Url          = $url
        LanUrl       = $lanUrl
        LocalIp      = (Get-LocalIP)
        ApiStatus    = $apiStatus
        Admin        = (Test-Admin)
        DockerCli    = (Test-DockerCli)
        Engine       = (Test-DockerEngine)
        DiskFreeGb   = (Get-DiskFreeGb)
        Containers   = $containers
        EnvIssues    = $envIssues
        Findings     = $findings
        LastBackup   = if ($backup) { $backup.Name } else { '' }
        FirewallRule = (Test-FirewallRule)
        LogFile      = $Script:LogPath
        CheckedAt    = (Get-Date).ToString('s')
    }
}

function Test-EnvStale {
    $result = Invoke-SetupNative -Tokens @('inspect', '2arbolitos-backend', '--format', '{{range .Config.Env}}{{println .}}{{end}}') -TimeoutSec 15
    if ($result.ExitCode -ne 0) { return $false }

    $containerJwt = ''
    foreach ($line in (([string]$result.Out) -split "`r?`n")) {
        if ($line -like 'JWT_SECRET=*') { $containerJwt = ($line -replace '^JWT_SECRET=', '').Trim() }
    }
    $fileJwt = Get-EnvValue -Key 'JWT_SECRET' -Default ''
    if (-not $containerJwt) { return $false }
    return ($containerJwt -ne $fileJwt)
}

function Get-PreviousDbPassword {
    $result = Invoke-SetupNative -Tokens @('inspect', '2arbolitos-db', '--format', '{{range .Config.Env}}{{println .}}{{end}}') -TimeoutSec 15
    if ($result.ExitCode -ne 0) { return '' }
    foreach ($line in (([string]$result.Out) -split "`r?`n")) {
        if ($line -like 'MYSQL_ROOT_PASSWORD=*') {
            return ($line -replace '^MYSQL_ROOT_PASSWORD=', '').Trim()
        }
    }
    return ''
}

function Get-RepairFindings {
    $rows = New-Object System.Collections.ArrayList
    $mode = Get-Mode

    if ($mode -eq 'portable') {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'portable'
            Severity = 'info'
            Title    = 'Instalacion portable detectada'
            Detail   = 'El instalador visual gestiona Docker. En modo portable usa start.bat y el panel de control.'
            Fix      = ''
            FixLabel = ''
        })
        return $rows
    }

    if ($mode -eq 'missing') {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'nofiles'
            Severity = 'bad'
            Title    = 'No se encontro una instalacion en esta carpeta'
            Detail   = 'Falta docker-compose.yml o server/. Comprueba que estes en la carpeta correcta.'
            Fix      = ''
            FixLabel = ''
        })
        return $rows
    }

    $envFile = Join-Path $Script:Root '.env'
    if (-not (Test-Path -LiteralPath $envFile)) {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'env'
            Severity = 'bad'
            Title    = 'Falta la configuracion (.env)'
            Detail   = 'Sin .env no se pueden generar los secretos ni arrancar los contenedores.'
            Fix      = 'env'
            FixLabel = 'Crear configuracion'
        })
    } else {
        $issues = (Get-EnvIssues).Issues
        if ($issues.Count -gt 0) {
            $parts = @()
            foreach ($issue in $issues) {
                if ($issue -eq 'missing') { $parts += 'archivo ausente' }
                elseif ($issue -eq 'bom') { $parts += 'marca BOM al inicio' }
                elseif ($issue -eq 'default-secret') { $parts += 'secreto por defecto' }
                elseif ($issue -eq 'ip-stale') { $parts += 'IP de red desactualizada' }
                elseif ($issue -eq 'bad-port') { $parts += 'puerto invalido' }
                elseif ($issue -like 'missing-key:*') { $parts += 'falta ' + ($issue -replace '^missing-key:', '') }
                elseif ($issue -like 'duplicate:*') { $parts += 'clave repetida: ' + ($issue -replace '^duplicate:', '') }
                else { $parts += $issue }
            }
            [void]$rows.Add([pscustomobject]@{
                Id       = 'env'
                Severity = 'warn'
                Title    = 'La configuracion tiene problemas'
                Detail   = ($parts -join ', ')
                Fix      = 'env'
                FixLabel = 'Corregir configuracion'
            })
        }
    }

    if (-not (Test-DockerCli)) {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'docker'
            Severity = 'bad'
            Title    = 'Docker no esta instalado'
            Detail   = 'Instala Docker Desktop desde docker.com y vuelve a abrir este instalador.'
            Fix      = ''
            FixLabel = ''
        })
        return $rows
    }

    if (-not (Test-DockerEngine)) {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'engine'
            Severity = 'bad'
            Title    = 'Docker Desktop no esta corriendo'
            Detail   = 'El motor de Docker no responde.'
            Fix      = 'engine'
            FixLabel = 'Iniciar Docker'
        })
        return $rows
    }

    $ps = Get-ComposePs
    $missing = 0
    $stopped = 0
    foreach ($service in @('db', 'backend', 'frontend')) {
        if (-not $ps.ContainsKey($service)) {
            $missing++
            continue
        }
        $item = $ps[$service]
        if ($item.State -ne 'running') {
            $stopped++
            [void]$rows.Add([pscustomobject]@{
                Id       = 'stopped-' + $service
                Severity = 'warn'
                Title    = "El contenedor $service esta detenido"
                Detail   = [string]$item.Status
                Fix      = 'start'
                FixLabel = 'Iniciar sistema'
            })
        } elseif ($item.Health -and $item.Health -ne 'healthy') {
            [void]$rows.Add([pscustomobject]@{
                Id       = 'unhealthy-' + $service
                Severity = 'warn'
                Title    = "El contenedor $service no esta sano"
                Detail   = [string]$item.Status
                Fix      = 'start'
                FixLabel = 'Reiniciar'
            })
        }
    }

    if ($missing -eq 3) {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'notcreated'
            Severity = 'warn'
            Title    = 'El sistema no esta instalado'
            Detail   = 'No hay contenedores creados todavia.'
            Fix      = 'install'
            FixLabel = 'Instalar'
        })
    }

    if ($missing -eq 0 -and $stopped -eq 0) {
        if (Test-EnvStale) {
            [void]$rows.Add([pscustomobject]@{
                Id       = 'stale'
                Severity = 'warn'
                Title    = 'Los contenedores usan una configuracion vieja'
                Detail   = 'El .env cambio despues de crearlos.'
                Fix      = 'recreate'
                FixLabel = 'Recrear contenedores'
            })
        }

        $api = Test-HttpStatus -Url ((Get-AccessUrl) + '/api/health') -TimeoutSec 4
        if ($api -ne 200) {
            $logs = Get-LogsSnapshot -Service 'backend' -Tail 60
            $info = Get-FailureInfo -Text $logs
            $fix = 'restart'
            if ($info.Code -eq 'DB_PASSWORD') { $fix = 'dbpass' }
            elseif ($info.Code -eq 'ENV_STALE') { $fix = 'recreate' }
            [void]$rows.Add([pscustomobject]@{
                Id       = 'api'
                Severity = 'bad'
                Title    = 'El sistema no responde'
                Detail   = $info.Title
                Fix      = $fix
                FixLabel = 'Intentar reparar'
            })
        }
    }

    $port = [int](Get-FrontendPort)
    if ($port -gt 0) {
        $owner = Get-PortOwner -Port $port
        if ($owner -and $owner.Name -notmatch 'docker|com\.docker') {
            $isOurs = ($ps.ContainsKey('frontend') -and $ps['frontend'].State -eq 'running')
            if (-not $isOurs) {
                [void]$rows.Add([pscustomobject]@{
                    Id       = 'port'
                    Severity = 'warn'
                    Title    = "El puerto $port esta ocupado"
                    Detail   = "Lo usa $($owner.Name) (PID $($owner.Pid))."
                    Fix      = 'port'
                    FixLabel = 'Elegir otro puerto'
                })
            }
        }
    }

    if (-not (Test-FirewallRule)) {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'firewall'
            Severity = 'info'
            Title    = 'Falta la regla de firewall'
            Detail   = 'Los celulares de la red local podrian no poder entrar.'
            Fix      = if (Test-Admin) { 'firewall' } else { '' }
            FixLabel = if (Test-Admin) { 'Permitir en firewall' } else { 'Requiere administrador' }
        })
    }

    $disk = Get-DiskFreeGb
    if ($disk -gt 0 -and $disk -lt 5) {
        [void]$rows.Add([pscustomobject]@{
            Id       = 'disk'
            Severity = 'warn'
            Title    = 'Queda poco espacio en disco'
            Detail   = "$disk GB libres. Docker necesita al menos 5 GB."
            Fix      = ''
            FixLabel = ''
        })
    }

    return $rows
}

