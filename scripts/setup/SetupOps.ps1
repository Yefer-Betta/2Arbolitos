function New-AppIcon {
    $png = Join-Path $Script:Root 'public\pwa-192x192.png'
    if (-not (Test-Path -LiteralPath $png)) { return '' }

    $dir = Join-Path $env:LOCALAPPDATA '2Arbolitos'
    $ico = Join-Path $dir 'app.ico'
    if (Test-Path -LiteralPath $ico) { return $ico }

    try {
        [void](New-Item -ItemType Directory -Path $dir -Force)
        Add-Type -AssemblyName System.Drawing
        $image = [System.Drawing.Image]::FromFile($png)
        try {
            $bitmap = New-Object System.Drawing.Bitmap($image, 64, 64)
            $handle = $bitmap.GetHicon()
            $icon = [System.Drawing.Icon]::FromHandle($handle)
            $stream = [System.IO.File]::Create($ico)
            try { $icon.Save($stream) } finally { $stream.Close() }
            $icon.Dispose()
            $bitmap.Dispose()
        } finally {
            $image.Dispose()
        }
        return $ico
    } catch {
        return ''
    }
}

function New-DesktopShortcut {
    $url = Get-AccessUrl
    $desktop = [Environment]::GetFolderPath('Desktop')
    if (-not $desktop) { $desktop = Join-Path $env:USERPROFILE 'Desktop' }
    if (-not (Test-Path -LiteralPath $desktop)) { return $null }

    $path = Join-Path $desktop '2Arbolitos POS.url'
    $icon = New-AppIcon

    $lines = @(
        '[InternetShortcut]',
        "URL=$url",
        'IDList=',
        'HotKey=0'
    )
    if ($icon) { $lines += "IconFile=$icon" }
    $lines += 'IconIndex=0'

    if ($Script:DryRunMode) {
        Write-Log "SIMULADO: acceso directo en $path"
        return $path
    }

    [System.IO.File]::WriteAllText($path, (($lines -join "`r`n") + "`r`n"), $Script:Utf8NoBom)
    Write-Log "Acceso directo creado: $path"
    return $path
}

