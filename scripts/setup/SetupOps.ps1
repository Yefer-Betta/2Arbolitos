function Install-Arbolitos {
    param([int]$Port = 0, [switch]$SkipShortcut)

    $plan = @(
        @{ id = 'preflight'; label = 'Requisitos del equipo' },
        @{ id = 'env';      label = 'Configuracion (.env)' },
        @{ id = 'firewall'; label = 'Acceso desde la red' },
        @{ id = 'build';    label = 'Construccion de imagenes' },
        @{ id = 'start';    label = 'Arranque de contenedores' },
        @{ id = 'health';   label = 'Espera de la base de datos' },
        @{ id = 'verify';   label = 'Verificacion del sistema' },
        @{ id = 'shortcut'; label = 'Acceso directo en el escritorio' }
    )
    Write-Event -Type 'plan' -Data @{ steps = $plan }

    Write-Event -Type 'step' -Data @{ id = 'preflight'; state = 'run'; text = 'Comprobando Docker...' }

    if (-not (Test-DockerCli)) {
        Write-Event -Type 'step' -Data @{ id = 'preflight'; state = 'bad'; text = 'Docker no esta instalado' }
        Stop-Setup -Code 'DOCKER_MISSING' -Title 'Docker no esta instalado' `
            -Detail 'Este instalador necesita Docker Desktop.' `
            -Hints @(
                'Descargalo en https://www.docker.com/products/docker-desktop/ e instalalo.',
                'Despues vuelve a abrir este instalador.'
            )
    }

    if (-not (Test-DockerEngine)) {
        Write-Event -Type 'log' -Data @{ text = 'Docker no responde; intentando abrirlo...' }
        if (Open-DockerDesktop) {
            $deadline = (Get-Date).AddSeconds(120)
            while ((Get-Date) -lt $deadline) {
                Start-Sleep -Seconds 3
                if (Test-DockerEngine -Force) { break }
            }
        }
        if (-not (Test-DockerEngine -Force)) {
            Write-Event -Type 'step' -Data @{ id = 'preflight'; state = 'bad'; text = 'Docker no responde' }
            Stop-Setup -Code 'ENGINE_OFF' -Title 'Docker Desktop no esta corriendo' `
                -Detail 'El motor de Docker no responde.' `
                -Hints @(
                    'Abre Docker Desktop y espera a que diga "Engine running".',
                    'Vuelve a intentarlo.'
                )
        }
    }

    $freeGb = Get-DiskFreeGb
    if ($freeGb -gt 0 -and $freeGb -lt 5) {
        Write-Event -Type 'log' -Data @{ text = "Aviso: quedan $freeGb GB libres en disco." }
    }
    Write-Event -Type 'step' -Data @{ id = 'preflight'; state = 'ok'; text = 'Docker listo' }

    Write-Event -Type 'step' -Data @{ id = 'env'; state = 'run'; text = 'Preparando la configuracion...' }
    $envResult = Initialize-Env -Port $Port
    Write-Event -Type 'step' -Data @{ id = 'env'; state = 'ok'; text = "Configuracion lista (puerto $($envResult.Port))" }
    if ($envResult.Backup) {
        Write-Event -Type 'log' -Data @{ text = 'Se guardo una copia de la configuracion anterior en .env.bak' }
    }

    if (Test-Admin) {
        Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'run'; text = 'Configurando el firewall...' }
        if (Add-FirewallRule -Port $envResult.Port) {
            Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'ok'; text = "Puerto $($envResult.Port) permitido en la red local" }
        } else {
            Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'skip'; text = 'No se pudo configurar el firewall (no es bloqueante)' }
        }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'firewall'; state = 'skip'; text = 'Firewall: se necesita ejecutar como administrador' }
    }

    Write-Event -Type 'step' -Data @{ id = 'build'; state = 'run'; text = 'Construyendo las imagenes (la primera vez tarda varios minutos)...' }
    $build = Invoke-StreamCompose -Tokens @('build') -TimeoutSec 2400
    if ($build.ExitCode -ne 0) {
        $info = Get-FailureInfo -Text (([string]$build.Out) + "`n" + ([string]$build.Err))
        Write-Event -Type 'step' -Data @{ id = 'build'; state = 'bad'; text = $info.Title }
        Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
    }
    Write-Event -Type 'step' -Data @{ id = 'build'; state = 'ok'; text = 'Imagenes listas' }

    Write-Event -Type 'step' -Data @{ id = 'start'; state = 'run'; text = 'Arrancando los contenedores...' }
    $up = Invoke-SetupNative -Tokens @('compose', 'up', '-d') -TimeoutSec 300

    if ($up.ExitCode -ne 0) {
        $text = ([string]$up.Out) + "`n" + ([string]$up.Err)
        if ($text -match 'is already in use by container|Conflict\. The container name') {
            Write-Event -Type 'log' -Data @{ text = 'Se detectaron contenedores de un intento anterior: limpiando...' }
            [void](Invoke-SetupNative -Tokens @('compose', 'down', '--remove-orphans') -TimeoutSec 120)
            $up = Invoke-SetupNative -Tokens @('compose', 'up', '-d') -TimeoutSec 300
        }
    }

    if ($up.ExitCode -ne 0) {
        $info = Get-FailureInfo -Text (([string]$up.Out) + "`n" + ([string]$up.Err))
        Write-Event -Type 'step' -Data @{ id = 'start'; state = 'bad'; text = $info.Title }
        Stop-Setup -Code $info.Code -Title $info.Title -Detail $info.Detail -Hints $info.Hints
    }
    Write-Event -Type 'step' -Data @{ id = 'start'; state = 'ok'; text = 'Contenedores arrancados' }

    Write-Event -Type 'step' -Data @{ id = 'health'; state = 'run'; text = 'Esperando a que la base de datos responda...' }

    if (Test-EnvStale) {
        Write-Event -Type 'log' -Data @{ text = 'Los contenedores usan un .env viejo: recreando backend y frontend...' }
        [void](Invoke-SetupNative -Tokens @('compose', 'up', '-d', '--force-recreate', 'backend', 'frontend') -TimeoutSec 240)
    }

    $health = Wait-SystemHealth -TimeoutSec 180
    if (-not $health.Ok) {
        $info = Get-FailureInfo -Text ([string]$health.Logs)
        $detail = $info.Detail
        if ($info.Code -eq 'UNKNOWN') {
            if ($health.Broken -eq 'timeout') {
                $detail = 'El sistema no respondio en 3 minutos.'
            } else {
                $detail = "El contenedor $($health.Broken) se detuvo."
            }
        }
        Write-Event -Type 'step' -Data @{ id = 'health'; state = 'bad'; text = $info.Title }
        Stop-Setup -Code $info.Code -Title $info.Title -Detail $detail -Hints $info.Hints
    }
    Write-Event -Type 'step' -Data @{ id = 'health'; state = 'ok'; text = 'Base de datos y API respondiendo' }

    Write-Event -Type 'step' -Data @{ id = 'verify'; state = 'run'; text = 'Comprobando el acceso...' }
    $page = Test-HttpStatus -Url (Get-AccessUrl) -TimeoutSec 8
    if ($page -ne 200) {
        Write-Event -Type 'step' -Data @{ id = 'verify'; state = 'bad'; text = 'La pagina no responde' }
        Stop-Setup -Code 'HTTP' -Title 'La pagina no responde' -Detail "El servidor web devolvio $page." `
            -Hints @('Revisa el contenedor frontend en la carpeta logs.')
    }
    $login = Test-ApiLogin -BaseUrl (Get-AccessUrl)
    if ($login -eq 0) {
        Write-Event -Type 'step' -Data @{ id = 'verify'; state = 'bad'; text = 'La API no responde' }
        Stop-Setup -Code 'HTTP' -Title 'La API no responde' -Detail 'El frontend carga pero el backend no contesta.' `
            -Hints @('Revisa los registros del backend en la carpeta logs.')
    }
    $loginText = if ($login -eq 200) { 'Acceso verificado' } else { "API operativa (HTTP $login)" }
    Write-Event -Type 'step' -Data @{ id = 'verify'; state = 'ok'; text = $loginText }

    if (-not $SkipShortcut) {
        Write-Event -Type 'step' -Data @{ id = 'shortcut'; state = 'run'; text = 'Creando el acceso directo...' }
        if (New-DesktopShortcut) {
            Write-Event -Type 'step' -Data @{ id = 'shortcut'; state = 'ok'; text = 'Acceso directo "2Arbolitos POS" creado' }
        } else {
            Write-Event -Type 'step' -Data @{ id = 'shortcut'; state = 'skip'; text = 'No se pudo crear el acceso directo' }
        }
    } else {
        Write-Event -Type 'step' -Data @{ id = 'shortcut'; state = 'skip'; text = 'Acceso directo omitido' }
    }

    Write-Event -Type 'done' -Data @{
        message = 'Instalacion completada'
        url     = (Get-AccessUrl)
        lanUrl  = (Get-LanUrl)
        port    = $envResult.Port
        logFile = $Script:LogPath
    }
}

