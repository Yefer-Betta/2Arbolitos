/**
 * Valores de ejemplo que nunca deben usarse en producción.
 * Incluye los fallbacks que generaban el paquete portable y los .env.example.
 */
const FORBIDDEN_JWT_SECRETS = new Set([
  'tu_secreto_jwt_aqui_muy_seguro_cambialo',
  'super_secret_jwt_change_this_in_production',
  '2arbolitos_jwt_autogenerated',
  '2arbolitos_cambia_este_secreto',
  'cambia_este_secreto_por_uno_seguro',
]);

function assertJwtSecret() {
  const secret = (process.env.JWT_SECRET || '').trim();
  const isProduction = process.env.NODE_ENV === 'production';

  let problem = null;
  if (!secret) {
    problem = 'JWT_SECRET no está definido';
  } else if (FORBIDDEN_JWT_SECRETS.has(secret.toLowerCase())) {
    problem = 'JWT_SECRET usa un valor de ejemplo';
  } else if (secret.length < 32) {
    problem = 'JWT_SECRET es demasiado corto (mínimo 32 caracteres)';
  }

  if (!problem) return;

  if (isProduction) {
    throw new Error(`${problem}. Genera uno con: openssl rand -hex 32`);
  }
  console.warn(`⚠️  ${problem}. En producción el servidor no arrancará así.`);
}

function resolveTrustProxy() {
  const raw = process.env.TRUST_PROXY;
  if (raw === undefined || String(raw).trim() === '') {
    // En Docker hay exactamente un salto (Nginx). En portable no hay proxy.
    return process.env.DOCKER === 'true' ? 1 : false;
  }

  const value = String(raw).trim().toLowerCase();
  if (value === 'true') return true;
  if (value === 'false' || value === '0') return false;

  const hops = Number(value);
  if (Number.isInteger(hops) && hops > 0) return hops;

  // Subred o lista separada por comas: Express la acepta como string.
  return String(raw).trim();
}

